--   * Продажа 1005 участвует в ДВУХ акциях — задвоение при группировке по
--     акциям.
--   * Продажа 1007 не участвует ни в одной — теряется при INNER JOIN с мостом.
--   * Остатки заданы на три дня подряд: сумма по датам бессмысленна.
--   * 2026-02-23 — праздник и одновременно понедельник: признак нельзя
--     вывести из самой даты.

INSERT INTO dim_date (date_key, day_of_week, is_weekend, is_holiday, month_start)
SELECT
    d::date,
    extract(isodow FROM d)::integer,
    extract(isodow FROM d) >= 6,
    d::date IN (DATE '2026-01-01', DATE '2026-01-07', DATE '2026-02-23'),
    date_trunc('month', d)::date
FROM generate_series(DATE '2026-01-01', DATE '2026-03-31', interval '1 day') AS d;

